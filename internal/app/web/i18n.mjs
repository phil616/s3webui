export function normalizeLocale(value) {
  return String(value).toLowerCase().startsWith("zh") ? "zh" : "en";
}
export function translate(locale, key, params = {}) {
  const template = messages[normalizeLocale(locale)][key] ?? messages.en[key];
  if (template === undefined) throw new Error(`Missing translation: ${key}`);
  return template.replace(/\{(\w+)\}/g, (_, name) =>
    String(params[name] ?? `{${name}}`),
  );
}
export function initialLocale(
  storage,
  languages = globalThis.navigator?.languages ?? ["en"],
) {
  try {
    const saved = (storage ?? globalThis.localStorage)?.getItem(
      "s3webui-locale",
    );
    if (saved === "zh" || saved === "en") return saved;
  } catch {}
  return normalizeLocale(languages[0] ?? "en");
}
export function formatSize(bytes, locale) {
  const value = Math.max(0, Number(bytes) || 0);
  const unit = Math.min(4, Math.floor(Math.log2(Math.max(1, value)) / 10));
  return (
    new Intl.NumberFormat(locale === "zh" ? "zh-CN" : "en", {
      maximumFractionDigits: 2,
    }).format(value / 1024 ** unit) +
    " " +
    ["B", "KiB", "MiB", "GiB", "TiB"][unit]
  );
}
export function formatDate(value, locale) {
  if (!value) return "";
  const d = new Date(value);
  return Number.isNaN(d.valueOf())
    ? String(value)
    : new Intl.DateTimeFormat(locale === "zh" ? "zh-CN" : "en", {
        dateStyle: "medium",
        timeStyle: "short",
      }).format(d);
}
